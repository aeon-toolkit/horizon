def get_processes(family: str | None = None, names: list[str] | None = None):
    """Return a list of processes filtered by ``family`` and/or ``names``.

    Parameters
    ----------
    family : {"arima", "ets", "all", None}
        Restrict to one family. ``None`` or ``"all"`` returns both.
    names : list of str or None
        Restrict to these process names.

    Returns
    -------
    list of Process
    """
    processes = list(ALL_PROCESSES.values())
    if family not in (None, "all"):
        processes = [p for p in processes if p.family == family]
    if names:
        unknown = set(names) - set(ALL_PROCESSES)
        if unknown:
            raise ValueError(f"unknown process names {sorted(unknown)}")
        processes = [p for p in processes if p.name in names]
    return processes
