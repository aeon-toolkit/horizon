"""Simulated data generating processes (DGPs) for forecaster comparison.

Everything here is a *known* generating process, so we can compare toolkits on
data where the correct model family is known and the only differences between
implementations are model selection, parameter estimation and speed.

Two families are provided:

``arima``
    Non-seasonal ARIMA(p, d, q) processes. aeon's :class:`AutoARIMA` is
    non-seasonal, so for a fair fight all competitors are also configured
    non-seasonal and the DGPs contain no seasonality.
``ets``
    State space exponential smoothing processes in the Hyndman taxonomy,
    ETS(error, trend, seasonality), following the recursions in [1]_.

References
----------
.. [1] R. J. Hyndman, A. B. Koehler, J. K. Ord and R. D. Snyder, Forecasting
   with Exponential Smoothing: The State Space Approach. Springer, 2008.
"""

from __future__ import annotations

from dataclasses import dataclass, field
