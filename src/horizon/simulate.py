@dataclass(frozen=True)
class Process:
    """A named simulated generating process.

    Parameters
    ----------
    name : str
        Short identifier used in file names and result tables.
    family : str
        Either ``"arima"`` or ``"ets"``. Determines which set of forecasters is
        compared on this process.
    seasonal_period : int
        True seasonal period of the process, 1 if non-seasonal. Passed to the
        competitor forecasters that require it, and used as the denominator lag
        for MASE.
    sampler : callable
        ``sampler(n, rng) -> np.ndarray`` of shape ``(n,)``.
    description : str
        Human readable description for the README/plots.
    """

    name: str
    family: str
    seasonal_period: int
    sampler: Callable[[int, np.random.Generator], np.ndarray] = field(repr=False)
    description: str = ""

    def sample(self, n: int, random_state: int) -> np.ndarray:
        """Draw a single series of length ``n`` using ``random_state`` as seed."""
        rng = np.random.default_rng(random_state)
        y = np.asarray(self.sampler(n, rng), dtype=np.float64)
        if y.shape != (n,):
            raise ValueError(f"{self.name} returned shape {y.shape}, expected ({n},)")
        if not np.all(np.isfinite(y)):
            raise ValueError(f"{self.name} produced non-finite values")
        return y


def simulate_arima(
    n: int,
    rng: np.random.Generator,
    ar: tuple[float, ...] = (),
    ma: tuple[float, ...] = (),
    d: int = 0,
    sigma: float = 1.0,
    const: float = 0.0,
    offset: float = 100.0,
    burn_in: int = 500,
) -> np.ndarray:
    """Simulate an ARIMA(p, d, q) series.

    The stationary ARMA part is generated by direct recursion

    .. math:: z_t = c + \\sum_i \\phi_i z_{t-i} + e_t + \\sum_j \\theta_j e_{t-j}

    with ``e_t ~ N(0, sigma^2)``, a burn-in period that is discarded, and the
    result then differenced-in-reverse (cumulatively summed) ``d`` times.

    Parameters
    ----------
    n : int
        Length of the returned series.
    rng : np.random.Generator
        Source of randomness.
    ar : tuple of float
        AR coefficients, must define a stationary process.
    ma : tuple of float
        MA coefficients.
    d : int
        Order of integration applied after generating the ARMA part.
    sigma : float
        Innovation standard deviation.
    const : float
        Constant term of the ARMA recursion.
    offset : float
        Added to the final series so values are comfortably positive, which
        multiplicative statsmodels/sktime models require.
    burn_in : int
        Number of initial observations discarded.

    Returns
    -------
    np.ndarray
        Series of shape ``(n,)``.
    """
    p, q = len(ar), len(ma)
    total = n + burn_in
    e = rng.normal(0.0, sigma, size=total + q)
    z = np.zeros(total, dtype=np.float64)
    ar = np.asarray(ar, dtype=np.float64)
    ma = np.asarray(ma, dtype=np.float64)
    for t in range(total):
        value = const + e[t + q]
        for i in range(p):
            if t - i - 1 >= 0:
                value += ar[i] * z[t - i - 1]
        for j in range(q):
            value += ma[j] * e[t + q - j - 1]
        z[t] = value
    z = z[burn_in:]
    for _ in range(d):
        z = np.cumsum(z)
    return z + offset


def _seasonal_start(sp: int, amplitude: float, seasonal_type: str) -> np.ndarray:
    """Build a deterministic starting seasonal state of length ``sp``."""
    if sp <= 1:
        return np.zeros(1, dtype=np.float64)
    wave = amplitude * np.sin(2.0 * np.pi * np.arange(sp) / sp)
    if seasonal_type == "mul":
        # Multiplicative seasonal indices average to one and stay positive.
        s = 1.0 + wave
        return np.clip(s, 0.2, None)
    # Additive seasonal indices average to zero.
    return wave - wave.mean()


def simulate_ets(
    n: int,
    rng: np.random.Generator,
    error: str = "add",
    trend: str | None = None,
    seasonal: str | None = None,
    sp: int = 1,
    alpha: float = 0.3,
    beta: float = 0.05,
    gamma: float = 0.1,
    phi: float = 0.95,
    sigma: float = 1.0,
    level0: float = 100.0,
    trend0: float = 0.2,
    seasonal_amplitude: float = 0.2,
    burn_in: int = 100,
) -> np.ndarray:
    """Simulate from an ETS state space model.

    Parameters
    ----------
    n : int
        Length of the returned series.
    rng : np.random.Generator
        Source of randomness.
    error : {"add", "mul"}
        Error type. ``"add"`` gives ``y_t = mu_t + e_t``, ``"mul"`` gives
        ``y_t = mu_t (1 + e_t)``.
    trend : {None, "add", "damped"}
        Trend type. ``"damped"`` is an additive trend damped by ``phi``.
    seasonal : {None, "add", "mul"}
        Seasonality type.
    sp : int
        Seasonal period. Ignored when ``seasonal`` is None.
    alpha, beta, gamma, phi : float
        Level, trend, seasonal and damping smoothing parameters.
    sigma : float
        Innovation standard deviation. For multiplicative error this is the
        standard deviation of the *relative* error, so it should be small
        (e.g. 0.02) to keep the series positive.
    level0, trend0 : float
        Initial level and trend states.
    seasonal_amplitude : float
        Amplitude of the initial seasonal state. Interpreted relative to the
        level for additive seasonality.
    burn_in : int
        Number of initial observations discarded.

    Returns
    -------
    np.ndarray
        Series of shape ``(n,)``.
    """
    if error not in ("add", "mul"):
        raise ValueError(f"error must be 'add' or 'mul', saw {error}")
    if trend not in (None, "add", "damped"):
        raise ValueError(f"trend must be None, 'add' or 'damped', saw {trend}")
    if seasonal not in (None, "add", "mul"):
        raise ValueError(f"seasonal must be None, 'add' or 'mul', saw {seasonal}")
    if seasonal is not None and sp < 2:
        raise ValueError("sp must be >= 2 for a seasonal model")

    has_trend = trend is not None
    damping = phi if trend == "damped" else 1.0
    m = sp if seasonal is not None else 1
    amp = seasonal_amplitude * (level0 if seasonal == "add" else 1.0)
    s = _seasonal_start(m, amp, seasonal or "add")

    level = float(level0)
    b = float(trend0) if has_trend else 0.0
    total = n + burn_in
    out = np.empty(total, dtype=np.float64)
    eps = rng.normal(0.0, sigma, size=total)

    for t in range(total):
        b_d = damping * b
        mu_level = level + b_d
        s_old = s[t % m] if seasonal is not None else 0.0
        if seasonal == "add":
            mu = mu_level + s_old
        elif seasonal == "mul":
            mu = mu_level * s_old
        else:
            mu = mu_level

        if error == "add":
            e = eps[t]
            out[t] = mu + e
            if seasonal == "mul":
                level = mu_level + alpha * e / s_old
                b_new = b_d + beta * e / s_old
                s[t % m] = s_old + gamma * e / mu_level
            else:
                level = mu_level + alpha * e
                b_new = b_d + beta * e
                if seasonal == "add":
                    s[t % m] = s_old + gamma * e
        else:
            e = eps[t]
            out[t] = mu * (1.0 + e)
            if seasonal == "add":
                level = mu_level + alpha * mu * e
                b_new = b_d + beta * mu * e
                s[t % m] = s_old + gamma * mu * e
            else:
                level = mu_level * (1.0 + alpha * e)
                b_new = b_d + beta * mu_level * e
                if seasonal == "mul":
                    s[t % m] = s_old * (1.0 + gamma * e)
        b = b_new if has_trend else 0.0

    return out[burn_in:]


def _positive(sampler: Callable[[int, np.random.Generator], np.ndarray]):
    """Wrap a sampler so the returned series is strictly positive and finite.

    Multiplicative ETS models in statsmodels (and therefore sktime) require
    strictly positive data, and multiplicative state space recursions can
    occasionally wander non-positive. Rather than silently changing the DGP we
    redraw with a fresh stream, and only as a last resort shift the series.
    """

    def wrapped(n: int, rng: np.random.Generator) -> np.ndarray:
        for _ in range(20):
            y = sampler(n, rng)
            if np.all(np.isfinite(y)) and np.min(y) > 0.0:
                return y
        y = sampler(n, rng)
        y = np.nan_to_num(y, nan=1.0, posinf=1.0, neginf=1.0)
        shift = 1.0 - np.min(y)
        return y + shift if shift > 0 else y

    return wrapped


