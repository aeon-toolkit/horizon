"""Build the paper's tables (tables/*.tex) from the committed result CSVs.

    python papers/windowed-ets-arima/make_tables.py
"""

from __future__ import annotations

from pathlib import Path

import numpy as np
import pandas as pd

HERE = Path(__file__).parent
RES = HERE.parents[1] / "results" / "aeon-8585c7bf"
OUT = HERE / "tables"
FORECASTERS = ["AutoARIMA", "AutoETS", "ARIMA", "ETS"]
FNAME = {"AutoARIMA": r"\texttt{AutoARIMA}", "AutoETS": r"\texttt{AutoETS}",
         "ARIMA": r"\texttt{ARIMA}(1,0,1)", "ETS": r"\texttt{ETS}(A,N,N)"}
SCHEME = {
    "full": "Whole series", "mean": "Mean", "median": "Median", "trimmed": "Trimmed mean (20\\%)",
    "inv_mse": "Inverse in-sample MSE", "inv_rel_mae": "Inverse in-sample relative MAE",
    "inv_rel_mae2": "Inverse squared in-sample relative MAE",
    "akaike_n100": "Akaike-style weights ($n_0=100$)", "best_insample": "Best in-sample window",
    "inv_oos_mse": "Inverse out-of-sample MSE", "median_best_half": "Median of better half",
    "mean_min300": "Mean, $w\\geq300$", "median_min300": "Median, $w\\geq300$",
    "inv_mse_min300": "Inverse in-sample MSE, $w\\geq300$",
    "inv_oos_mse_min300": "Inverse out-of-sample MSE, $w\\geq300$",
}
SCHEME_ORDER = ["full", "mean", "median", "trimmed", "inv_mse", "inv_rel_mae", "inv_rel_mae2",
                "akaike_n100", "best_insample", "inv_oos_mse", "median_best_half",
                "mean_min300", "median_min300", "inv_mse_min300", "inv_oos_mse_min300"]


def f3(x) -> str:
    return "--" if pd.isna(x) else f"{x:.3f}"


def bold_min(vals: list[float]) -> list[str]:
    m = np.nanmin(vals)
    return [rf"\textbf{{{f3(v)}}}" if np.isclose(v, m) else f3(v) for v in vals]


def write(name: str, body: str) -> None:
    OUT.mkdir(exist_ok=True)
    (OUT / name).write_text(f"% generated by make_tables.py from results/aeon-8585c7bf; do not edit\n{body}")


def lssh_windows() -> None:
    """Relative MAE against window length, per forecaster (LSSH-99, all series)."""
    s = pd.read_csv(RES / "lssh99-window" / "summary.csv")
    ws = [m for m in s.method.unique() if m.startswith("w=")]
    ws = sorted(ws, key=lambda m: int(m[2:]))
    cols = ["full"] + ws
    head = " & ".join(["Whole"] + [m[2:] for m in ws])
    rows = []
    for f in FORECASTERS:
        d = s[s.forecaster == f].set_index("method")
        rows.append(f"{FNAME[f]} & " + " & ".join(bold_min([d.loc[c, "all"] for c in cols])) + r" \\")
    body = rf"""\begin{{tabular}}{{l{'c' * len(cols)}}}
\toprule
 & \multicolumn{{{len(cols)}}}{{c}}{{Training window (observations)}} \\
\cmidrule(lr){{2-{len(cols) + 1}}}
Forecaster & {head} \\
\midrule
{chr(10).join(rows)}
\bottomrule
\end{{tabular}}
"""
    write("lssh_windows.tex", body)


def lssh_main() -> None:
    """Whole series, best fixed window, selection, mean, median, oracle (LSSH-99)."""
    s = pd.read_csv(RES / "lssh99-window" / "summary.csv")
    c = pd.read_csv(RES / "window-combine" / "lssh99_summary.csv")
    rows = []
    for f in FORECASTERS:
        d = s[s.forecaster == f].set_index("method")
        e = c[c.forecaster == f].set_index("method")
        fixed = d[d.index.str.startswith("w=")]["all"]
        bw = fixed.idxmin()
        vals = [d.loc["full", "all"], fixed.min(), d.loc["validation", "all"], d.loc["rolling", "all"],
                e.loc["mean", "all"], e.loc["median", "all"], e.loc["inv_oos_mse", "all"]]
        cells = bold_min(vals)
        cells[1] += f" ({bw[2:]})"
        rows.append(f"{FNAME[f]} & " + " & ".join(cells) + f" & {f3(d.loc['oracle', 'all'])}" + r" \\")
    body = r"""\begin{tabular}{lccccccc|c}
\toprule
 & Whole & Best fixed & \multicolumn{2}{c}{Selection} & \multicolumn{3}{c|}{Combination} & \\
\cmidrule(lr){4-5}\cmidrule(lr){6-8}
Forecaster & series & window & validation & rolling & mean & median & inv.\ OOS MSE & Oracle \\
\midrule
""" + "\n".join(rows) + r"""
\bottomrule
\end{tabular}
"""
    write("lssh_main.tex", body)


def lssh_schemes() -> None:
    """Every combination scheme: relative MAE and series better/worse than whole series."""
    c = pd.read_csv(RES / "window-combine" / "lssh99_summary.csv")
    rows = []
    best = {f: c[(c.forecaster == f)]["all"].min() for f in FORECASTERS}
    for m in SCHEME_ORDER:
        cells = []
        for f in FORECASTERS:
            r = c[(c.forecaster == f) & (c.method == m)].iloc[0]
            v = f3(r["all"])
            if np.isclose(r["all"], best[f]):
                v = rf"\textbf{{{v}}}"
            bw = "" if m == "full" else f" ({int(r.better)}/{int(r.worse)})"
            star = "" if m == "full" or pd.isna(r.p_holm) or r.p_holm >= 0.05 else "$^*$"
            cells.append(v + star + bw)
        rows.append(f"{SCHEME[m]} & " + " & ".join(cells) + r" \\")
    body = r"""\begin{tabular}{l""" + "c" * len(FORECASTERS) + r"""}
\toprule
Combination & """ + " & ".join(FNAME[f] for f in FORECASTERS) + r""" \\
\midrule
""" + "\n".join(rows) + r"""
\bottomrule
\end{tabular}
"""
    write("lssh_schemes.tex", body)


def lssh_periods() -> None:
    """Relative MAE by seasonal period (LSSH-99), whole series vs median vs best."""
    sys_path = HERE.parents[1] / "scripts"
    import sys
    sys.path.insert(0, str(sys_path))
    from aaltd_experiments import period_of
    per = pd.read_csv(RES / "window-combine" / "lssh99_per_problem.csv")
    per["period"] = per.problem.map(period_of)
    label = {7: "Daily (7)", 12: "Monthly (12)", 24: "Hourly (24)", 48: "Half-hourly (48)",
             52: "Weekly (52)", 144: "10-minute (144)", 1440: "Minutely (1440)"}

    def g(x):
        x = x.dropna()
        return float(np.exp(np.log(x).mean())) if len(x) else np.nan
    rows = []
    for p in sorted(per.period.unique()):
        d = per[per.period == p]
        n = d.problem.nunique()
        cells = []
        for f in ["AutoARIMA", "AutoETS"]:
            e = d[d.forecaster == f]
            cells += [f3(g(e["full"])), f3(g(e["median"])), f3(g(e["inv_oos_mse"]))]
        rows.append(f"{label[p]} & {n} & " + " & ".join(cells) + r" \\")
    body = r"""\begin{tabular}{lrcccccc}
\toprule
 & & \multicolumn{3}{c}{\texttt{AutoARIMA}} & \multicolumn{3}{c}{\texttt{AutoETS}} \\
\cmidrule(lr){3-5}\cmidrule(lr){6-8}
Sampling (period) & Series & whole & median & inv.\ OOS & whole & median & inv.\ OOS \\
\midrule
""" + "\n".join(rows) + r"""
\bottomrule
\end{tabular}
"""
    write("lssh_periods.tex", body)


def m4_main() -> None:
    """M4 (>= 500 points): OWA by frequency, whole series and combinations."""
    path = RES / "window-combine" / "m4_owa.csv"
    if not path.exists():
        return
    t = pd.read_csv(path)
    sel = pd.read_csv(RES / "m4-window-min300" / "owa.csv")
    freqs = ["yearly", "quarterly", "monthly", "weekly", "daily", "hourly", "all"]
    show = [("full", "Whole series"), ("validation", "Holdout selection ($w\\geq300$)"),
            ("mean", "Mean"), ("median", "Median"), ("median_best_half", "Median of better half"),
            ("inv_oos_mse", "Inverse holdout MSE"),
            ("inv_oos_mse_min300", "Inverse holdout MSE, $w\\geq300$"),
            ("inv_mse", "Inverse in-sample MSE")]
    rows = []
    for f in ["AutoARIMA", "AutoETS"]:
        rows.append(rf"\multicolumn{{8}}{{l}}{{{FNAME[f]}}} \\")
        for m, lab in show:
            src = sel if m == "validation" else t
            r = src[(src.forecaster == f) & (src.method == m)]
            if r.empty:
                continue
            r = r.iloc[0]
            rows.append(f"\\quad {lab} & " + " & ".join(f3(r.get(q)) for q in freqs) + r" \\")
        rows.append(r"\addlinespace")
    body = r"""\begin{tabular}{lccccccc}
\toprule
 & Yearly & Quarterly & Monthly & Weekly & Daily & Hourly & All \\
\midrule
""" + "\n".join(rows[:-1]) + r"""
\bottomrule
\end{tabular}
"""
    write("m4_main.tex", body)


def m4_schemes() -> None:
    path = RES / "window-combine" / "m4_owa.csv"
    if not path.exists():
        return
    t = pd.read_csv(path)
    best = {f: t[(t.forecaster == f) & (t.method != "Naive2")]["all"].min() for f in FORECASTERS}
    rows = []
    for m in SCHEME_ORDER:
        cells = []
        for f in FORECASTERS:
            r = t[(t.forecaster == f) & (t.method == m)]
            if r.empty:
                cells.append("--")
                continue
            r = r.iloc[0]
            v = f3(r["all"])
            if np.isclose(r["all"], best[f]):
                v = rf"\textbf{{{v}}}"
            if m != "full" and pd.notna(r.get("better")):
                star = "$^*$" if r.p_value < 0.05 / (len(SCHEME_ORDER) - 1) else ""
                v += f"{star} ({int(r.better)}/{int(r.worse)})"
            cells.append(v)
        rows.append(f"{SCHEME[m]} & " + " & ".join(cells) + r" \\")
    body = r"""\begin{tabular}{l""" + "c" * len(FORECASTERS) + r"""}
\toprule
Combination & """ + " & ".join(FNAME[f] for f in FORECASTERS) + r""" \\
\midrule
""" + "\n".join(rows) + r"""
\bottomrule
\end{tabular}
"""
    write("m4_schemes.tex", body)


if __name__ == "__main__":
    lssh_windows()
    lssh_main()
    lssh_schemes()
    lssh_periods()
    m4_main()
    m4_schemes()
    print(sorted(p.name for p in OUT.glob("*.tex")))
